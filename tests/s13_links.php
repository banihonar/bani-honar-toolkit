<?php
require __DIR__ . '/harness.php';
require __DIR__ . '/wpposts.php';
if(!function_exists('get_page_by_path')){ function get_page_by_path($p,$o=OBJECT,$t='page'){ return null; } }
$p = BHTK_Plugin::instance(); $p->set_module_enabled('link-shortener', true);
BHTK_Links::install();
$db = $GLOBALS['wpdb']->raw(); $db->exec('DELETE FROM ' . BHTK_Links::table());
$a = BHTK_Links::create('https://example.com/one', 6, 'Ab33', 'first note');
$b = BHTK_Links::create('https://example.com/two', 6, 'ab33', '');
$c = BHTK_Links::create('https://example.org/%25percent_100', 6, 'Pct', "50% off and _under_");
t_ok('create returns rows', is_object($a) || is_array($a) || is_int($a) || is_numeric($a), json_encode($a));
$row = BHTK_Links::get_by_code('Ab33');
t_ok('get_by_code is case sensitive', $row && 'https://example.com/one' === $row->target && BHTK_Links::get_by_code('ab33')->target==='https://example.com/two');
t_ok('get_by_code unknown gives nothing', ! BHTK_Links::get_by_code('Zz99Zz'));
t_ok('get by id', BHTK_Links::get((int)$row->id)->code === 'Ab33' && ! BHTK_Links::get(999999));
list($rows,$total) = BHTK_Links::query();
t_ok('query without search: all rows, newest first', 3===$total && 3===count($rows) && 'Pct'===$rows[0]->code, json_encode(array_column($rows,'code')));
list($rows,$total) = BHTK_Links::query('', 2, 2);
t_ok('query paging', 3===$total && 1===count($rows) && 'Ab33'===$rows[0]->code, json_encode(array_column($rows,'code')));
list($rows,$total) = BHTK_Links::query('example.org');
t_ok('query search by target', 1===$total && 'Pct'===$rows[0]->code);
list($rows,$total) = BHTK_Links::query('first note');
t_ok('query search by note', 1===$total && 'Ab33'===$rows[0]->code);
list($rows,$total) = BHTK_Links::query('under');
t_ok('query search by note words', 1===$total && 'Pct'===$rows[0]->code, json_encode(array_column($rows,'code')));
list($rows,$total) = BHTK_Links::query("x'; DROP TABLE " . BHTK_Links::table() . ';--');
t_ok('quotes in the search words are harmless', 0===$total && 0===count($rows) && 3===(int)$db->query('SELECT COUNT(*) FROM '.BHTK_Links::table())->fetchColumn());
$st = BHTK_Links::stats();
t_ok('stats: links and clicks', 3===$st['links'] && 0===$st['clicks'], json_encode($st));
$track = new ReflectionMethod('BHTK_Links','track'); $track->setAccessible(true);
$_SERVER['REQUEST_METHOD']='GET'; $track->invoke(null,(int)$row->id); $track->invoke(null,(int)$row->id);
$_SERVER['REQUEST_METHOD']='HEAD'; $track->invoke(null,(int)$row->id);
t_ok('click counter: two GET clicks counted, HEAD ignored, last click stored', 2===(int)BHTK_Links::get((int)$row->id)->clicks && ''!==(string)BHTK_Links::get((int)$row->id)->last_click);
t_ok('stats count the clicks', 2===BHTK_Links::stats()['clicks']);
BHTK_Links::update((int)$row->id,'https://example.com/changed','new note');
t_ok('update', 'https://example.com/changed'===BHTK_Links::get((int)$row->id)->target);
BHTK_Links::delete((int)$row->id);
t_ok('delete', ! BHTK_Links::get((int)$row->id) && 2===BHTK_Links::query()[1]);
echo ($GLOBALS['t_fails'] ?? 0) ? "\nFAILED: {$GLOBALS['t_fails']}\n" : "\nLINKS OK\n";
